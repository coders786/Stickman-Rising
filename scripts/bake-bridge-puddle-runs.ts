/** Regenerate after changing the shared procedural drainage material. */
import { writeFileSync } from 'node:fs'
import { bakeBridgePuddleRuns } from '../src/game/stage/bridge-material'

const runs = bakeBridgePuddleRuns(), lines: string[] = []
for (let i = 0; i < runs.length; i += 24) lines.push(`  ${runs.slice(i, i + 24).join(', ')},`)
writeFileSync('src/game/stage/bridge-puddle-runs.ts', `// Generated by scripts/bake-bridge-puddle-runs.ts. [x, worldY, width, height].\nexport const BRIDGE_PUDDLE_RUNS = [\n${lines.join('\n')}\n] as const\n`)
