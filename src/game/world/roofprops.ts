/** Seeded maintenance-shoulder furniture. Solid housings also feed the light field. */
import { h01 } from './buildings'
import { PRACTICAL_SIGN_X, PRACTICAL_LAMP_X, BEACON_X, type PointLight } from './lightfield'

export type RoofPropKind = 'barrier' | 'cabinet' | 'marker' | 'bulb'

export interface RoofProp {
  kind: RoofPropKind
  x: number
  /** Deck y of the prop's base (0 = the deck; props stand on it). */
  y: number
  w: number
  h: number
  phase: number
  /** The bulb prop lights; every other prop is furniture. */
  lit: boolean
}

export interface RoofPropSet {
  props: RoofProp[]
  /** Lights generated by the props (currently only the bulb). */
  lights: PointLight[]
}

const KIND_TABLE: ReadonlyArray<readonly [RoofPropKind, number]> = [
  ['barrier', .33], ['cabinet', .17], ['marker', .47], ['bulb', .03],
]

function pickKind(r: number): RoofPropKind {
  let acc = 0
  for (const [k, p] of KIND_TABLE) {
    acc += p
    if (r <= acc) return k
  }
  return 'marker'
}

/** Size per kind. Height is capped by the "must not block the fight" rule. */
function sizeFor(kind: RoofPropKind, r: number): { w: number; h: number } {
  switch (kind) {
    case 'barrier': return {w:38+18*r,h:17+3*r}
    case 'cabinet': return {w:15+8*r,h:23+7*r}
    case 'marker': return {w:6,h:14+8*r}
    case 'bulb': return { w: 6, h: 46 }
  }
}

/**
 * Place the props. Deterministic from the run seed; `count` is the tier's
 * budget, so a low-tier device simply gets fewer of the same roof (never a
 * different roof).
 *
 * Placement rules, in order of importance:
 *   · never within 110 px of a stage practical (the streetlight's pole and the
 *     stairwell's doorway are geometry, and a crate inside them looks glued on);
 *   · never within 70 px of another prop (clutter is spaced, not stacked);
 *   · spread across the deck with jitter so the spacing does not read as a grid.
 */
export function makeRoofProps(
  seed: number,
  opts: { count: number; x0: number; x1: number; deckY?: number },
): RoofPropSet {
  const n = Math.max(0, Math.floor(opts.count))
  const x0 = opts.x0
  const x1 = opts.x1
  const y = opts.deckY ?? 0
  const props: RoofProp[] = []
  const lights: PointLight[] = []
  if (n === 0 || !(x1 > x0)) return { props, lights }
  const span = x1 - x0
  let bulbs = 0
  for (let i = 0; i < n; i++) {
    const slot = x0 + (span * (i + 0.5)) / n
    // ±45 % of a slot: enough jitter to break the grid, not enough to collide
    // with the neighbour's slot.
    const jitter = (h01(i, 17, seed) - 0.5) * (span / n) * 0.9
    let x = slot + jitter
    if (Math.abs(x - PRACTICAL_LAMP_X) < 110) x += x < PRACTICAL_LAMP_X ? -130 : 130
    if (Math.abs(x - PRACTICAL_SIGN_X) < 110) x += x < PRACTICAL_SIGN_X ? -130 : 130
    if (Math.abs(x-BEACON_X)<40) x=BEACON_X-45
    if (x < x0 + 12 || x > x1 - 12) continue
    let clash = false
    for (const p of props) {
      if (Math.abs(p.x - x) < 70) { clash = true; break }
    }
    if (clash) continue
    let kind = pickKind(h01(i, 31, seed))
    if (kind === 'bulb' && bulbs >= 1) kind = 'marker'
    const size = sizeFor(kind, h01(i, 43, seed))
    const lit = kind === 'bulb'
    if (lit) bulbs++
    props.push({ kind, x, y, w: size.w, h: size.h, phase: h01(i, 59, seed), lit })
    if (lit) {
      // The bulb hangs at the TOP of its stand, so the light is ~46 px up.
      lights.push({
        id: `roof:bulb:${i}`,
        x,
        y: y - size.h + 6,
        kind: 'bulb',
        radius: 250 + 40 * h01(i, 67, seed),
        gain: 0.55 + 0.3 * h01(i, 71, seed),
        flicker: 0.1 + 0.25 * h01(i, 73, seed),
        flickerHz: 1.3 + 0.9 * h01(i, 79, seed),
        phase: h01(i, 83, seed) * 6.283,
      })
    }
  }
  /* GUARANTEE ONE BULB on a full roof. A 2 % weight would mean most runs never
   * see the one prop that is also a light — and "the run changes where the light
   * is" is the whole point of generating props per run, not a 1-in-50 event. If
   * the roll missed, the last plain prop becomes the bulb (same slot, same
   * spacing), and its light is built from the same formula as a rolled one. */
  if (bulbs === 0 && props.length >= 8) {
    const i = props.length - 1
    const host = props[i]
    host.kind = 'bulb'
    host.w = 6
    host.h = 46
    host.lit = true
    lights.push({
      id: `roof:bulb:${i}`,
      x: host.x,
      y: host.y - host.h + 6,
      kind: 'bulb',
      radius: 250 + 40 * h01(i, 67, seed),
      gain: 0.55 + 0.3 * h01(i, 71, seed),
      flicker: 0.1 + 0.25 * h01(i, 73, seed),
      flickerHz: 1.3 + 0.9 * h01(i, 79, seed),
      phase: h01(i, 83, seed) * 6.283,
    })
  }
  return { props, lights }
}

/* Constant inks — the deck's palette. A prop is a silhouette with one edge of
 * moon on it; anything brighter competes with the fighters. */
const INK_BODY = '#0b131b'
const INK_DARK = '#080f16'
const MOON_EDGE = 'rgba(150,185,220,0.22)'
/** THE CITY IS BELOW YOU. A rooftop object at night is lit from UNDERNEATH by
 *  the street it stands above — that underside edge is the single cue that says
 *  "six floors up" instead of "a crate on a dark floor". */
const CITY_EDGE = 'rgba(255,190,128,0.30)'
const CITY_UNDER = 'rgba(255,170,102,0.10)'
const BULB_GLOW = '255,214,160'

/**
 * Draw the visible props. Returns how many were drawn (the ledger of this pass,
 * used by the tests and the debug overlay).
 *
 * `shadow` turns on the contact chip under each prop — one small ellipse fill,
 * the same grounding language the fighters use.
 */
export function drawRoofProps(
  ctx: CanvasRenderingContext2D,
  props: readonly RoofProp[],
  viewL: number,
  viewR: number,
  shadow: boolean,
  bulbGain: number,
): number {
  let drawn = 0
  ctx.save()
  for (const p of props) {
    if (p.x + p.w < viewL - 40 || p.x - p.w > viewR + 40) continue
    const bx = p.x - p.w * 0.5
    const by = p.y - p.h
    if (shadow) {
      // contact chip + the city's bounce spilling around the base: the object
      // blocks the light from below, so it is darkest exactly where it meets the
      // deck and warm at its outer edge.
      ctx.globalAlpha = 0.34
      ctx.fillStyle = '#000'
      ctx.beginPath()
      ctx.ellipse(p.x, p.y + 1, p.w * 0.62, 2.6, 0, 0, Math.PI * 2)
      ctx.fill()
      ctx.globalAlpha = 1
      ctx.fillStyle = CITY_UNDER
      ctx.beginPath()
      ctx.ellipse(p.x, p.y + 1.5, p.w * 0.92, 4.2, 0, 0, Math.PI * 2)
      ctx.fill()
    }
    switch (p.kind) {
      case 'barrier': {
        ctx.fillStyle='#38434c';ctx.beginPath();ctx.moveTo(bx,p.y);ctx.lineTo(bx+4,by+6);ctx.lineTo(bx+5,by);ctx.lineTo(bx+p.w-5,by);ctx.lineTo(bx+p.w,p.y);ctx.fill()
        ctx.fillStyle=MOON_EDGE;ctx.fillRect(bx+5,by,p.w-10,1)
        ctx.fillStyle='#9a8154';ctx.fillRect(bx+8,by+4,7,2);break
      }
      case 'cabinet': {
        ctx.fillStyle='#28333e';ctx.fillRect(bx,by,p.w,p.h)
        ctx.fillStyle=MOON_EDGE;ctx.fillRect(bx,by,p.w,1)
        ctx.fillStyle=INK_DARK;for(let i=0;i<3;i++)ctx.fillRect(bx+4,by+4+2*i,p.w-8,1);break
      }
      case 'marker': {
        ctx.fillStyle='#454c51';ctx.fillRect(bx+1,by,4,p.h)
        ctx.fillStyle='#ceb581';ctx.fillRect(bx+1,by+3,4,4);break
      }
      case 'bulb': {
        // Battery work lamp: the LED and the field share a fixed socket
        // and the same evaluated gain. No second oscillator in the sprite.
        ctx.fillStyle=INK_DARK;ctx.fillRect(p.x-1,by+6,2,p.h-6)
        ctx.fillStyle=MOON_EDGE;ctx.fillRect(p.x-4,by+3,8,7)
        ctx.globalCompositeOperation='lighter'
        ctx.globalAlpha=Math.min(1,bulbGain)
        ctx.fillStyle = `rgb(${BULB_GLOW})`
        ctx.beginPath()
        ctx.arc(p.x, by + 6, 3.2, 0, Math.PI * 2)
        ctx.fill()
        ctx.globalAlpha = 0.17 * bulbGain
        ctx.beginPath()
        ctx.arc(p.x, by + 6, 13, 0, Math.PI * 2)
        ctx.fill()
        ctx.globalAlpha = 1
        ctx.globalCompositeOperation = 'source-over'
        break
      }
    }
    // THE UNDERSIDE — a warm line where the city's light grazes the object.
    // Only for things that actually stand on legs or a plinth: a bulb's cable
    // does not catch light from below, a condenser's skirt does.
    if (p.kind==='barrier'||p.kind==='cabinet') {
      ctx.fillStyle = CITY_EDGE
      ctx.fillRect(bx, p.y - 1.5, p.w, 1.5)
    }
    drawn++
  }
  ctx.restore()
  return drawn
}
